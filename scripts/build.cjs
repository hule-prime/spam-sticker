const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../extension");
const source = ["core.js", "content.js"].map(file => fs.readFileSync(path.join(root, file), "utf8")).join("\n");
// Bundle the isolated world separately: Chromium can deduplicate a file listed in two worlds.
fs.writeFileSync(path.join(root, "content.bundle.js"), "// Generated by npm run build. Edit core.js or content.js.\n" + source);
console.log("Built isolated content script");
